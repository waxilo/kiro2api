// 概览弹窗的统一契约。
//
// 与 `views/types.ts` 同构，但少两样东西：**没有导航名字**（弹窗不进导航），
// **没有 head 的自由发挥空间**（关闭按钮由外壳统一渲染在右上角，弹窗自己只加动作按钮）。
// 这样两个弹窗、以及将来第三个弹窗，关闭按钮的位置与形状必然一致。
import type { AppState, ModalId } from '../../state/app-state';

export interface ModalSpec {
  id: ModalId;
  /** 弹窗标题。 */
  title: string;
  /** 标题下的一句话说明，回答「这个数是从哪来的」。 */
  desc: string;
  /** 标题左侧的图标（`ICON` 里的内联 SVG）。 */
  icon: string;
  /**
   * 主体容器的修饰类名（`is-<variant>`）。
   *
   * 存在的理由只有一个：清单类弹窗要「工具栏钉在顶上、只有清单滚」，得让样式表能
   * 单独选中这一种主体，而不是给所有弹窗都套一层 flex 收缩链。
   */
  variant?: string;
  /**
   * 高度档位。
   *
   * 弹窗高度**必须定死**：内容会随用户操作整块换掉（搜索过滤、同步清单、查询额度），
   * 靠内容撑高的话，在弹窗里敲一个字整块卡片就矮一截。两档不是审美选择，是内容的量级：
   * - `list`（默认）装得下两行以上的清单：460px；
   * - `compact` 只有一块结论（用量条这种）：380px。
   * 分档而不是统一高度，是为了让「额度」这类弹窗不顶着 460px 的下半屏空白。
   */
  size?: 'list' | 'compact';
  /** 标题右侧的动作区（同步模型 / 查询额度）；不需要就返回空串。返回已转义或受控的 HTML。 */
  head(state: AppState): string;
  /** 弹窗主体。返回已转义或受控的 HTML。 */
  body(state: AppState): string;
}
